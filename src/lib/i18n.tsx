const STRINGS: Record<Lang, Record<TextKey, string>> = { en, ko };
const STORAGE_KEY = 'lumi.lang';

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: TextKey) => string;
}

const I18nContext = createContext<I18n | null>(null);

/** A text in a given language, whatever the app shows now (typed words are read in both). */
export const textOf = (lang: Lang, key: TextKey): string => (lang === 'en' ? en : ko)[key];

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>('en');

  useEffect(() => {
    AsyncStorage.getItem(STORAGE_KEY)
      .then((v) => {
        if (v === 'en' || v === 'ko') setLangState(v);
      })
      .catch(() => {});
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    AsyncStorage.setItem(STORAGE_KEY, l).catch(() => {});
  }, []);

  const value = useMemo<I18n>(() => ({ lang, setLang, t: (key) => STRINGS[lang][key] }), [lang, setLang]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18n {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}
