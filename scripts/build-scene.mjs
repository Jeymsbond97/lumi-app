// Turns web/home3d.html into one self-contained HTML string for the app's WebView.
// The robot's own Wi-Fi has no internet, so three.js and the fonts are bundled in, nothing comes from a CDN.
// Run after editing the page: npm run scene
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { build } from 'esbuild';

const root = new URL('..', import.meta.url);
const require = createRequire(import.meta.url);
let html = readFileSync(new URL('web/home3d.html', root), 'utf8');

// 1. bundle the page script with three.js
const scriptRe = /<script type="module">([\s\S]*?)<\/script>/;
const source = html.match(scriptRe)[1];
const bundled = await build({
  stdin: { contents: source, resolveDir: new URL('web', root).pathname, loader: 'js' },
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2020',
  write: false,
  alias: { 'three/examples/jsm': 'three/examples/jsm' },
  logLevel: 'warning',
});
const js = bundled.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
html = html.replace(scriptRe, () => `<script>${js}</script>`);
html = html.replace(/<script type="importmap">[\s\S]*?<\/script>\s*/, '');

// 2. fonts: same faces the app uses, embedded
const face = (family, weight, file) => {
  const data = readFileSync(require.resolve(file)).toString('base64');
  return `@font-face{font-family:'${family}';font-weight:${weight};font-display:block;src:url(data:font/ttf;base64,${data}) format('truetype')}`;
};
const fonts = [
  face('Unbounded', 500, '@expo-google-fonts/unbounded/500Medium/Unbounded_500Medium.ttf'),
  face('Unbounded', 600, '@expo-google-fonts/unbounded/600SemiBold/Unbounded_600SemiBold.ttf'),
  face('Hanken Grotesk', 400, '@expo-google-fonts/hanken-grotesk/400Regular/HankenGrotesk_400Regular.ttf'),
  face('Hanken Grotesk', 500, '@expo-google-fonts/hanken-grotesk/500Medium/HankenGrotesk_500Medium.ttf'),
  face('Hanken Grotesk', 600, '@expo-google-fonts/hanken-grotesk/600SemiBold/HankenGrotesk_600SemiBold.ttf'),
].join('\n');
html = html.replace(/<link href="https:\/\/fonts\.googleapis\.com[^>]*>/, `<style>${fonts}</style>`);

if (/https?:\/\/(cdn|fonts)\./.test(html)) throw new Error('scene still points at the internet');

const out = `// Generated by scripts/build-scene.mjs from web/home3d.html. Do not edit by hand.\nexport const SCENE_HTML: string = ${JSON.stringify(html)};\n`;
writeFileSync(new URL('src/scene/sceneHtml.ts', root), out);
console.log(`scene: ${(html.length / 1024).toFixed(0)} KB, no internet needed`);
